"""Generate additive 0090 from the applied 0089 visit-work triggers.

Keep their mutations unchanged; only narrow each neighbor search to the exact
timestamp buckets before ordering UUID tokens without a token-bearing index.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[4]
SOURCE = (ROOT / 'migrations/core/0089_visit_work_cache.sql').read_text()


def candidate(sign):
    comparison, direction = ('<', 'DESC') if sign < 0 else ('>', 'ASC')
    previous = f'''(
 SELECT x.raw_id FROM vane_raw_events x WHERE x.context=cx.context AND (x.at_offset,x.token){comparison}(r.at_offset,r.token)
 ORDER BY x.at_offset {direction},x.token {direction} LIMIT 1)'''
    # A same-time neighbor wins over every strictly earlier/later timestamp.
    # If none exists, find the nearest timestamp through (context,at_offset),
    # then order only that bucket's complete, unchanged tokens. COALESCE is
    # lazy, so an available same-time neighbor needs no adjacent-bucket search.
    replacement = f'''COALESCE(
 (SELECT tied.raw_id FROM vane_raw_events tied
  WHERE tied.context=cx.context AND tied.at_offset=r.at_offset AND tied.token{comparison}r.token
  ORDER BY tied.token {direction} LIMIT 1),
 (SELECT adjacent.raw_id FROM vane_raw_events adjacent
  WHERE adjacent.context=cx.context AND adjacent.at_offset=(
   SELECT bucket.at_offset FROM vane_raw_events bucket
   WHERE bucket.context=cx.context AND bucket.at_offset{comparison}r.at_offset
   ORDER BY bucket.at_offset {direction} LIMIT 1)
  ORDER BY adjacent.token {direction} LIMIT 1))'''
    return previous, replacement


def trigger(name, signs):
    start = SOURCE.index(f'CREATE TRIGGER {name} ')
    end = SOURCE.find('\n\nCREATE TRIGGER ', start)
    result = SOURCE[start:end if end >= 0 else None].strip()
    for sign in signs:
        previous, replacement = candidate(sign)
        if result.count(previous) != 1:
            raise ValueError(f'Expected exactly one {sign} neighbor in {name}')
        result = result.replace(previous, replacement)
    return result


def generate():
    return '\n\n'.join([
        '''-- Keep exact raw rows and the (site,token) UUID uniqueness constraint.
-- Remove the redundant context-range prefix and avoid retaining UUID tokens
-- in the context/time index. Neighbor queries first select an indexed timestamp
-- bucket, then order its full tokens, including same-time neighbors.
-- Generated by src/vane/analytics/visits/generate-compact-indexes.py.''',
        'DROP INDEX vane_raw_context_range;',
        'DROP INDEX vane_raw_events_context_time;',
        'CREATE INDEX vane_raw_events_context_time ON vane_raw_events(context,at_offset);',
        'DROP TRIGGER vane_visit_append;',
        'DROP TRIGGER vane_visit_detail_change;',
        trigger('vane_visit_append', [-1, 1]),
        trigger('vane_visit_detail_change', [1]),
    ]) + '\n'


if __name__ == '__main__':
    (ROOT / 'migrations/core/0090_compact_event_indexes.sql').write_text(generate())
