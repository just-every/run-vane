"""Generate the additive bulk scope/queue migration; normal writes stay exact."""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[5]


def generate():
    source = (ROOT / 'migrations/core/0087_visit_facts.sql').read_text()
    normal = re.search(r'CREATE TRIGGER vane_visit_raw_insert\b.*?\n END ;', source, re.S).group()
    normal = normal.replace('WHEN NEW.at_offset IS NOT NULL BEGIN',
                            'WHEN NEW.at_offset IS NOT NULL AND NOT EXISTS(SELECT 1 FROM vane_visit_bulk_scope) BEGIN')
    return '''-- Exact transaction-scoped native visit batching. Persistent scratch is
-- emptied inside the admitting D1 transaction; no raw occurrence is discarded.
-- Generated by src/vane/analytics/visits/bulk/generate.py.
CREATE TABLE vane_visit_bulk_scope(singleton INTEGER PRIMARY KEY CHECK(singleton=1));
CREATE TABLE vane_visit_bulk_chains(
 site INTEGER NOT NULL,day TEXT NOT NULL,visitor INTEGER NOT NULL,gap INTEGER NOT NULL,
 PRIMARY KEY(site,day,visitor)
) WITHOUT ROWID;
CREATE TABLE vane_visit_bulk_pages(
 raw_id INTEGER PRIMARY KEY,site INTEGER NOT NULL,day TEXT NOT NULL,visitor INTEGER NOT NULL,
 context INTEGER NOT NULL,at_offset INTEGER NOT NULL,token BLOB NOT NULL,at INTEGER NOT NULL,
 engaged INTEGER,scroll INTEGER NOT NULL,gap INTEGER NOT NULL,old_visit INTEGER,
 next_id INTEGER,old_on_page INTEGER,on_page INTEGER
);
CREATE INDEX vane_visit_bulk_pages_old ON vane_visit_bulk_pages(old_visit,context,old_on_page,scroll);
CREATE TABLE vane_visit_bulk_nodes(
 kind INTEGER NOT NULL,node_id INTEGER NOT NULL,site INTEGER NOT NULL,day TEXT NOT NULL,visitor INTEGER NOT NULL,
 started INTEGER NOT NULL,last_at INTEGER NOT NULL,last_signal INTEGER NOT NULL,
 first_raw INTEGER NOT NULL,last_raw INTEGER NOT NULL,pages INTEGER NOT NULL,engaged INTEGER NOT NULL,
 identity TEXT NOT NULL,first_on_page INTEGER NOT NULL,run INTEGER NOT NULL,visit INTEGER,
 PRIMARY KEY(kind,node_id)
) WITHOUT ROWID;
CREATE TABLE vane_visit_bulk_groups(
 site INTEGER NOT NULL,day TEXT NOT NULL,visitor INTEGER NOT NULL,run INTEGER NOT NULL,visit INTEGER NOT NULL UNIQUE,
 first_raw INTEGER NOT NULL,last_raw INTEGER NOT NULL,started INTEGER NOT NULL,last_at INTEGER NOT NULL,
 last_signal INTEGER NOT NULL,pages INTEGER NOT NULL,engaged INTEGER NOT NULL,identity TEXT NOT NULL,first_on_page INTEGER NOT NULL,
 PRIMARY KEY(site,day,visitor,run)
) WITHOUT ROWID;
DROP TRIGGER vane_visit_raw_insert;
''' + normal + '''
CREATE TRIGGER vane_visit_raw_bulk_insert AFTER INSERT ON vane_raw_events
 WHEN EXISTS(SELECT 1 FROM vane_visit_bulk_scope) BEGIN
 INSERT INTO vane_visit_work(raw_id,action)
 SELECT NEW.raw_id,'bulk' FROM vane_raw_contexts WHERE context=NEW.context AND kind='pageview';
 END ;
'''


if __name__ == '__main__':
    (ROOT / 'migrations/core/0091_bulk_visits.sql').write_text(generate())
