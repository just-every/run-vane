"""Generate additive 0095, gating raw insert maintenance before its body runs."""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[3]


def generate():
    source = (ROOT / 'migrations/core/0093_raw_groups.sql').read_text()
    trigger = re.search(
        r'CREATE TRIGGER vane_raw_occurrence_insert AFTER INSERT ON vane_raw_occurrences BEGIN\n(.*?)\n END ;',
        source, re.S,
    )
    if trigger is None:
        raise ValueError('0093 physical occurrence insert trigger is missing')
    normal, separator, bulk = trigger.group(1).rpartition('INSERT INTO vane_visit_work(raw_id,action)\n')
    if not separator or "SELECT NEW.raw_id,'bulk'" not in bulk:
        raise ValueError('0093 bulk queue statement is missing')
    # Preserve the complete analytics -> normal visit statement sequence. The
    # outer WHEN prevents any of these statements running for bulk occurrences;
    # its existing statement-local predicates remain semantically unchanged.
    return '''-- Skip normal per-occurrence maintenance at the trigger boundary
-- while a native batch owns the transaction-local bulk scope.
-- Generated by src/vane/raw/generate-bulk-insert.py.
DROP TRIGGER vane_raw_occurrence_insert;
CREATE TRIGGER vane_raw_occurrence_insert AFTER INSERT ON vane_raw_occurrences
 WHEN NOT EXISTS(SELECT 1 FROM vane_visit_bulk_scope) BEGIN
''' + normal.rstrip() + '''
 END ;
CREATE TRIGGER vane_raw_occurrence_bulk_insert AFTER INSERT ON vane_raw_occurrences
 WHEN EXISTS(SELECT 1 FROM vane_visit_bulk_scope) BEGIN
 INSERT INTO vane_visit_work(raw_id,action)
 SELECT NEW.raw_id,'bulk' FROM vane_raw_groups g
 JOIN vane_raw_contexts c ON c.context=g.context
 WHERE g.group_id=NEW.group_id AND c.kind='pageview';
 END ;
'''


if __name__ == '__main__':
    (ROOT / 'migrations/core/0095_bulk_raw_insert.sql').write_text(generate())
