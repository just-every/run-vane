"""Generate additive 0096: visit-only group moves need only old-group GC."""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[3]


def guard(comparison):
    # Both rows must still exist. Either AFTER trigger may collect OLD before
    # SQLite evaluates the other's WHEN; a missing OLD must match neither arm.
    return f'''EXISTS(SELECT 1 FROM vane_raw_groups previous
 JOIN vane_raw_groups current ON current.group_id=NEW.group_id
 WHERE previous.group_id=OLD.group_id AND ({comparison}))'''


def generate():
    source = (ROOT / 'migrations/core/0093_raw_groups.sql').read_text()
    trigger = re.search(
        r'CREATE TRIGGER vane_raw_occurrence_update AFTER UPDATE OF group_id,site,token ON vane_raw_occurrences BEGIN\n(.*?)\n END ;',
        source, re.S,
    )
    if trigger is None:
        raise ValueError('0093 physical occurrence update trigger is missing')
    full = trigger.group(1)
    gc = re.search(r'DELETE FROM vane_raw_groups WHERE group_id=OLD.group_id\n AND NOT EXISTS\(SELECT 1 FROM vane_raw_occurrences WHERE group_id=OLD.group_id\);\s*$', full)
    if gc is None:
        raise ValueError('0093 terminal old-group collection is missing')
    changed = guard('previous.context!=current.context OR previous.at_offset IS NOT current.at_offset')
    same = guard('previous.context=current.context AND previous.at_offset IS current.at_offset')
    return '''-- Derived visit reassignment preserves context and exact timestamp.
-- Gate analytical/performance maintenance before entering its statement body.
-- Generated by src/vane/raw/generate-group-reassignment.py.
DROP TRIGGER vane_raw_occurrence_update;
CREATE TRIGGER vane_raw_occurrence_update AFTER UPDATE OF group_id,site,token ON vane_raw_occurrences
 WHEN ''' + changed + ''' BEGIN
''' + full + '''
 END ;
CREATE TRIGGER vane_raw_occurrence_reassign AFTER UPDATE OF group_id,site,token ON vane_raw_occurrences
 WHEN ''' + same + ''' BEGIN
''' + gc.group().rstrip() + '''
 END ;
'''


if __name__ == '__main__':
    (ROOT / 'migrations/core/0096_raw_group_reassignment.sql').write_text(generate())
