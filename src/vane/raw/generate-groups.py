"""Generate additive 0093 from the effective, immutable 0086–0092 definitions.

Only schema text is parsed: this generator neither opens nor migrates a database.
Physical occurrence keys survive ALTER TABLE so every existing FK keeps its row.
"""
from pathlib import Path
import re
import sqlite3

ROOT = Path(__file__).resolve().parents[3]


def definitions():
    active = {}
    for path in sorted((ROOT / 'migrations/core').glob('*.sql')):
        if not 86 <= int(path.name[:4]) <= 92:
            continue
        pending = ''
        for line in path.read_text().splitlines(True):
            pending += line
            if not sqlite3.complete_statement(pending):
                continue
            sql = re.sub(r'--[^\n]*', '', pending).strip()
            pending = ''
            match = re.match(r'(CREATE|DROP) (TRIGGER|VIEW) (\w+)', sql)
            if match:
                action, kind, name = match.groups()
                if action == 'DROP':
                    active.pop(name, None)
                else:
                    active[name] = (kind, sql)
    return active


def body(sql):
    return re.search(r'\bBEGIN\b(.*)\bEND\s*;', sql, re.S).group(1).strip()


def fields(sql):
    """Split SQL expressions, respecting parentheses and quoted strings."""
    result, start, depth, quoted = [], 0, 0, False
    for index, char in enumerate(sql):
        if char == "'":
            quoted = not quoted
        elif not quoted:
            if char == '(':
                depth += 1
            elif char == ')':
                depth -= 1
            elif char == ',' and depth == 0:
                result.append(sql[start:index].strip())
                start = index + 1
    return result + [sql[start:].strip()]


def group_match(context, at, visit, alias=''):
    p = alias + '.' if alias else ''
    return (f'{p}context={context} AND ({p}at_offset IS NULL)=({at} IS NULL) '
            f'AND coalesce({p}at_offset,0)=coalesce({at},0) '
            f'AND ({p}visit_id IS NULL)=({visit} IS NULL) '
            f'AND coalesce({p}visit_id,0)=coalesce({visit},0)')


def group_value(prefix, column):
    return f'(SELECT {column} FROM vane_raw_groups WHERE group_id={prefix}.group_id)'


def physical(sql):
    # NEW/OLD refer to a physical occurrence, while all ordinary SELECTs keep
    # using the compatibility view and its group/time and membership indexes.
    return re.sub(r'\b(NEW|OLD)\.(context|at_offset|visit_id)\b',
                  lambda m: group_value(*m.groups()), sql)


def generate():
    active = definitions()
    affected = {name: definition for name, definition in active.items()
                if 'vane_raw_events' in definition[1] or name in ('vane_raw_update', 'vane_raw_delete')}
    parts = ['''-- Exact repeated metadata, never repeated occurrence weights.
-- Generated by src/vane/raw/generate-groups.py. Applied history is unchanged.
-- Every full UUID/opaque ID and raw_id remains one actual physical row.
''']
    emit = parts.append
    # DROP VIEW also removes its INSTEAD OF triggers: remove triggers first.
    for kind in ('TRIGGER', 'VIEW'):
        for name, (actual, _) in affected.items():
            if actual == kind:
                emit(f'DROP {kind} {name};')
    emit('''ALTER TABLE vane_raw_events RENAME TO vane_raw_occurrences;
CREATE TABLE vane_raw_groups(
 group_id INTEGER PRIMARY KEY,context INTEGER NOT NULL REFERENCES vane_raw_contexts(context),
 at_offset INTEGER,visit_id INTEGER
);
CREATE UNIQUE INDEX vane_raw_groups_unique ON vane_raw_groups(context,(at_offset IS NULL),coalesce(at_offset,0),(visit_id IS NULL),coalesce(visit_id,0));
CREATE INDEX vane_raw_groups_context_time ON vane_raw_groups(context,at_offset);
CREATE INDEX vane_raw_groups_visit ON vane_raw_groups(visit_id) WHERE visit_id IS NOT NULL;
INSERT INTO vane_raw_groups(context,at_offset,visit_id)
 SELECT DISTINCT context,at_offset,visit_id FROM vane_raw_occurrences;
-- ADD COLUMN cannot declare a non-null REFERENCES column on populated SQLite
-- tables. Integrity triggers below enforce non-null; the FK enforces existence.
ALTER TABLE vane_raw_occurrences ADD COLUMN group_id INTEGER REFERENCES vane_raw_groups(group_id);
''')
    emit('UPDATE vane_raw_occurrences SET group_id=(SELECT group_id FROM vane_raw_groups g WHERE ' +
         group_match('vane_raw_occurrences.context', 'vane_raw_occurrences.at_offset', 'vane_raw_occurrences.visit_id', 'g') + ');')
    emit('''DROP INDEX vane_raw_events_context_time;
DROP INDEX vane_raw_events_visit;
ALTER TABLE vane_raw_occurrences DROP COLUMN context;
ALTER TABLE vane_raw_occurrences DROP COLUMN at_offset;
ALTER TABLE vane_raw_occurrences DROP COLUMN visit_id;
CREATE INDEX vane_raw_occurrences_group ON vane_raw_occurrences(group_id);
CREATE VIEW vane_raw_events AS SELECT e.raw_id,e.site,e.token,g.context,g.at_offset,g.visit_id
 FROM vane_raw_occurrences e JOIN vane_raw_groups g ON g.group_id=e.group_id;
''')
    for name, (kind, sql) in affected.items():
        if kind == 'VIEW':
            emit(sql)
    # The compatibility view interns one exact tuple before moving a physical
    # row. The physical trigger owns analytical/visit maintenance and GC.
    match = group_match('NEW.context', 'NEW.at_offset', 'NEW.visit_id')
    visit = '(CASE WHEN NEW.context IS NOT OLD.context OR NEW.at_offset IS NOT OLD.at_offset OR NEW.site IS NOT OLD.site OR NEW.token IS NOT OLD.token THEN NULL ELSE NEW.visit_id END)'
    update_match = group_match('NEW.context', 'NEW.at_offset', visit)
    emit(f'''CREATE TRIGGER vane_raw_event_insert INSTEAD OF INSERT ON vane_raw_events BEGIN
 INSERT OR IGNORE INTO vane_raw_groups(context,at_offset,visit_id)
 SELECT NEW.context,NEW.at_offset,NEW.visit_id WHERE NOT EXISTS(SELECT 1 FROM vane_raw_occurrences WHERE site=NEW.site AND token=NEW.token);
 INSERT INTO vane_raw_occurrences(raw_id,site,token,group_id)
 VALUES(NEW.raw_id,NEW.site,NEW.token,COALESCE((SELECT group_id FROM vane_raw_occurrences WHERE site=NEW.site AND token=NEW.token),(SELECT group_id FROM vane_raw_groups WHERE {match})));
END;
CREATE TRIGGER vane_raw_event_update INSTEAD OF UPDATE ON vane_raw_events BEGIN
 INSERT OR IGNORE INTO vane_raw_groups(context,at_offset,visit_id) VALUES(NEW.context,NEW.at_offset,{visit});
 UPDATE vane_raw_occurrences SET raw_id=NEW.raw_id,site=NEW.site,token=NEW.token,
 group_id=(SELECT group_id FROM vane_raw_groups WHERE {update_match}) WHERE raw_id=OLD.raw_id;
END;
CREATE TRIGGER vane_raw_event_delete INSTEAD OF DELETE ON vane_raw_events BEGIN
 DELETE FROM vane_raw_occurrences WHERE raw_id=OLD.raw_id;
END;''')
    # Logical INSERT must remain a physical INSERT immediately before the
    # changes() detail gate; routing that one statement through a view loses it.
    logical = active['vane_raw_insert'][1]
    original = re.search(r'INSERT INTO vane_raw_events\(site,token,context,at_offset\)\s*VALUES\((.*?)\);', logical, re.S)
    site, token, context, at = fields(original.group(1))
    key = f'site={site} AND token={token}'
    lookup = group_match(context, at, 'NULL')
    replacement = f'''INSERT OR IGNORE INTO vane_raw_groups(context,at_offset,visit_id)
 SELECT {context},{at},NULL WHERE NOT EXISTS(SELECT 1 FROM vane_raw_occurrences WHERE {key});
 INSERT INTO vane_raw_occurrences(site,token,group_id)
 VALUES({site},{token},COALESCE((SELECT group_id FROM vane_raw_occurrences WHERE {key}),(SELECT group_id FROM vane_raw_groups WHERE {lookup})));'''
    emit(logical.replace(original.group(), replacement))
    raw_triggers = {name: sql for name, (kind, sql) in affected.items()
                    if kind == 'TRIGGER' and re.search(r'\bON vane_raw_events\b', sql)}
    for name, (kind, sql) in affected.items():
        if kind == 'TRIGGER' and name not in raw_triggers and name != 'vane_raw_insert':
            emit(sql)
    # Before triggers can observe OLD without racing any group collection.
    for name in ('vane_visit_raw_delete', 'vane_visit_raw_rewrite', 'vane_visit_perf_context_before'):
        sql = raw_triggers[name].replace(' ON vane_raw_events', ' ON vane_raw_occurrences')
        if name == 'vane_visit_raw_rewrite':
            sql = sql.replace('UPDATE OF context,at_offset', 'UPDATE OF group_id,site,token')
            sql = sql.replace('WHEN OLD.context IS NOT NEW.context OR OLD.at_offset IS NOT NEW.at_offset BEGIN',
                              'WHEN OLD.context IS NOT NEW.context OR OLD.at_offset IS NOT NEW.at_offset OR OLD.site IS NOT NEW.site OR OLD.token IS NOT NEW.token BEGIN')
            sql = sql.replace('BEGIN', '''BEGIN
 INSERT OR IGNORE INTO vane_visit_legacy(site,day,visitor)
 SELECT site,day,visitor FROM vane_raw_contexts WHERE context=NEW.context
 AND kind='pageview' AND visitor IS NOT NULL AND typeof(NEW.token)!='blob';''', 1)
        else:
            sql = sql.replace('UPDATE OF context ', 'UPDATE OF group_id ')
        emit(physical(sql))
    for action in ('INSERT', 'UPDATE'):
        emit(f'''CREATE TRIGGER vane_raw_group_required_{action.lower()} BEFORE {action} ON vane_raw_occurrences
 WHEN NEW.group_id IS NULL BEGIN SELECT RAISE(ABORT,'Raw occurrence requires an exact metadata group'); END;''')
    # One AFTER trigger per operation gives explicit ordering. The visit append
    # path may move NEW to a visited group recursively, collecting its old group.
    # Therefore analytics must consume NEW before visit assignment is invoked.
    analytics = body(raw_triggers['vane_raw_analytics_insert'])
    analytics = analytics.replace('WHERE c.context=NEW.context', 'WHERE c.context=NEW.context AND NOT EXISTS(SELECT 1 FROM vane_visit_bulk_scope)')
    normal = body(raw_triggers['vane_visit_raw_insert'])
    normal = normal.replace('context=NEW.context', 'context=NEW.context AND NEW.at_offset IS NOT NULL AND NOT EXISTS(SELECT 1 FROM vane_visit_bulk_scope)')
    normal = normal.replace('WHERE r.raw_id=NEW.raw_id', 'WHERE r.raw_id=NEW.raw_id AND r.at_offset IS NOT NULL AND NOT EXISTS(SELECT 1 FROM vane_visit_bulk_scope)')
    bulk = body(raw_triggers['vane_visit_raw_bulk_insert']).replace('context=NEW.context', 'context=NEW.context AND EXISTS(SELECT 1 FROM vane_visit_bulk_scope)')
    emit('CREATE TRIGGER vane_raw_occurrence_insert AFTER INSERT ON vane_raw_occurrences BEGIN\n' + physical(analytics + '\n' + normal + '\n' + bulk) + '\nEND;')
    def without_gc(sql):
        return re.sub(r'DELETE FROM vane_raw_contexts WHERE context=OLD.context[^;]*;', '', body(sql)).strip()
    gc = '''DELETE FROM vane_raw_groups WHERE group_id=OLD.group_id
 AND NOT EXISTS(SELECT 1 FROM vane_raw_occurrences WHERE group_id=OLD.group_id);'''
    emit('CREATE TRIGGER vane_raw_occurrence_delete AFTER DELETE ON vane_raw_occurrences BEGIN\n' + physical(without_gc(raw_triggers['vane_raw_analytics_delete'])) + '\n' + gc + '\nEND;')
    changed = '(NEW.context IS NOT OLD.context OR NEW.at_offset IS NOT OLD.at_offset)'
    analytics = without_gc(raw_triggers['vane_raw_analytics_update'])
    for prefix in ('OLD', 'NEW'):
        analytics = analytics.replace(f'WHERE c.context={prefix}.context', f'WHERE c.context={prefix}.context AND {changed}')
    perf = body(raw_triggers['vane_visit_perf_context_after']).replace('WHERE e.raw_id=NEW.raw_id', 'WHERE e.raw_id=NEW.raw_id AND NEW.context IS NOT OLD.context')
    # The view clears stale membership as it interns the new tuple. It must
    # not recursively UPDATE itself: SQLite can disable recursive triggers.
    emit('CREATE TRIGGER vane_raw_occurrence_update AFTER UPDATE OF group_id,site,token ON vane_raw_occurrences BEGIN\n' + physical(analytics + '\n' + perf) + '\n' + gc + '\nEND;')
    emit('''CREATE TRIGGER vane_raw_group_gc AFTER DELETE ON vane_raw_groups BEGIN
 DELETE FROM vane_raw_contexts WHERE context=OLD.context
 AND NOT EXISTS(SELECT 1 FROM vane_raw_groups WHERE context=OLD.context);
END;''')
    return re.sub(r'\b(CASE|END)\b', r' \1 ', '\n\n'.join(parts)) + '\n'


if __name__ == '__main__':
    (ROOT / 'migrations/core/0093_raw_groups.sql').write_text(generate())
